import UIKit
import XCTest

/// The tab bar's and sidebar's system-equivalent behaviors that the package's offscreen tests
/// cannot show (review rounds 1 and 2): Command-1/2/3 switch areas from a hardware keyboard; a long
/// press on a tab bar item at an accessibility text size shows the large content viewer, and
/// lifting the finger opens the item under it (also after sliding to another item), as on a system
/// tab bar; a long press on a control with the viewer activates it exactly once. They run in the
/// real app on the simulator; the device checks (checklist steps 12 and 17) stay.
@MainActor
final class AreaNavigationTests: XCTestCase {
    /// The area items in order of their shortcuts (Command-1, -2, -3).
    static let areas = ["Library", "Thoughts", "Inbox"]

    private func areaButton(_ app: XCUIApplication, _ label: String) -> XCUIElement {
        app.buttons.matching(NSPredicate(format: "label == %@", label)).firstMatch
    }

    /// Waits until `label`'s area item reports the selected trait.
    private func waitUntilSelected(_ app: XCUIApplication, _ label: String, seconds: Double = 10) -> Bool {
        let deadline = Date().addingTimeInterval(seconds)
        while Date() < deadline {
            let item = areaButton(app, label)
            if item.exists && item.isSelected { return true }
            Thread.sleep(forTimeInterval: 0.25)
        }
        return false
    }

    /// Command-1, -2 and -3 from a hardware keyboard select Library, Thoughts and Inbox (the tab bar
    /// on iPhone, the sidebar on iPad in regular width), and exactly one item is selected each time.
    func testHardwareKeyboardSwitchesAreas() {
        let app = Harness.launch(["-SylviaScreen", "library", "-SylviaAppearance", "light"])
        defer { app.terminate() }
        XCTAssertNotNil(Harness.audit(app, name: "library"))
        XCTAssertTrue(waitUntilSelected(app, "Library"), "Library is not selected at launch")
        // The simulator attaches its hardware keyboard on the first key event it synthesizes, and that
        // first event can be consumed by the attachment (the clean run of review round 1 lost
        // Command-2 this way while Command-3 and -1 worked). Escape, which the Library ignores,
        // attaches the keyboard first; then a pause lets the key commands register.
        app.typeKey(XCUIKeyboardKey.escape, modifierFlags: [])
        Thread.sleep(forTimeInterval: 1.5)
        XCTAssertTrue(waitUntilSelected(app, "Library"), "Escape changed the selected area")
        var rows: [String] = []
        // Thoughts, Inbox, then back to Library, so every shortcut changes the selection.
        for (key, label) in [("2", "Thoughts"), ("3", "Inbox"), ("1", "Library")] {
            app.typeKey(key, modifierFlags: .command)
            let selected = waitUntilSelected(app, label)
            XCTAssertTrue(selected, "Command-\(key) did not select \(label)")
            let others = Self.areas.filter { $0 != label && areaButton(app, $0).isSelected }
            XCTAssertTrue(others.isEmpty, "Command-\(key): \(others) also selected")
            let name = "command-\(key)-\(label.lowercased())"
            let path = Harness.screenshot(name, folder: "screens/\(Harness.deviceFolder)/keyboard")
            rows.append("| Command-\(key) | \(label) | \(selected ? "yes" : "no") | \(others.isEmpty ? "none" : others.joined(separator: ", ")) | \(path) |")
        }
        Harness.writeText("keyboard-shortcuts-\(Harness.deviceFolder)-simulator.md", """
            # Hardware keyboard: Command-1, -2, -3 switch areas

            Environment: \(Harness.simulatorEnvironment(defaultLabel: "iPhone 17")). Generated by \
            `AreaNavigationTests.testHardwareKeyboardSwitchesAreas` (XCUITest `typeKey(_:modifierFlags: .command)` \
            on the running catalog, prototype opened at the Library). "Selected" is the item's selected \
            accessibility trait as XCUITest reads it. This is a simulated keyboard event, not a physical \
            keyboard (checklist step 17 stays).

            | Keys | Area expected | Selected | Other items selected | Screenshot |
            | --- | --- | --- | --- | --- |
            \(rows.joined(separator: "\n"))
            """)
    }

    /// A long press on the Inbox tab bar item at the largest accessibility text size shows the large
    /// content viewer, and lifting the finger opens the Inbox (required since review round 2; a
    /// system tab bar does this). A second press starts on Thoughts and slides to Library before
    /// lifting: Library must open, and only it. The UI test cannot take a screenshot while it holds
    /// the press, so `21-design-catalog.sh` takes them from the host with `simctl io screenshot` on
    /// request (files in `SYLVIA_EVIDENCE_DIR/.lcv`): one before the press and one 2.5 s into a 6 s
    /// press. The test then compares the middle of the two images.
    func testLargeContentViewerOnTabBarItem() throws {
        XCTAssertEqual(UIDevice.current.userInterfaceIdiom, .phone, "the tab bar shows on iPhone")
        guard let evidence = Harness.evidenceDirectory else {
            throw XCTSkip("needs SYLVIA_EVIDENCE_DIR and the host helper of 21-design-catalog.sh")
        }
        let requests = evidence.appendingPathComponent(".lcv")
        let shots = evidence.appendingPathComponent("screens/\(Harness.deviceFolder)/lcv")
        let app = Harness.launch(["-SylviaScreen", "library"] + Variant.ax5.arguments)
        defer { app.terminate() }
        XCTAssertNotNil(Harness.audit(app, name: "library"))
        let inbox = areaButton(app, "Inbox")
        XCTAssertTrue(inbox.waitForExistence(timeout: 10))
        XCTAssertFalse(inbox.isSelected)

        // Two captures with nothing pressed (the control), then one during the press.
        try requestHostScreenshot("baseline-1", delay: 0, in: requests, wait: true)
        try requestHostScreenshot("baseline-2", delay: 0, in: requests, wait: true)
        try requestHostScreenshot("inbox-long-press", delay: 2.5, in: requests, wait: false)
        inbox.press(forDuration: 6)
        try waitForHostScreenshot("inbox-long-press", in: requests)

        let control = try changedFraction(shots.appendingPathComponent("baseline-1.png"),
                                          shots.appendingPathComponent("baseline-2.png"))
        let pressed = try changedFraction(shots.appendingPathComponent("baseline-1.png"),
                                          shots.appendingPathComponent("inbox-long-press.png"))
        XCTAssertLessThan(control, 0.01, "the screen changed without a press: \(control)")
        // The overlay is a light translucent panel over a light screen, so the change is moderate
        // (0.11 measured in the first run) against exactly 0 for the control.
        XCTAssertGreaterThan(pressed, 0.04, "no large content viewer in the middle of the screen: \(pressed)")
        // System bars activate the item under the finger when it lifts (review round 2: required).
        let openedOnLift = waitUntilSelected(app, "Inbox", seconds: 5)
        XCTAssertTrue(openedOnLift, "lifting the finger from the large content viewer did not open the Inbox")
        let othersAfterLift = Self.areas.filter { $0 != "Inbox" && areaButton(app, $0).isSelected }
        XCTAssertTrue(othersAfterLift.isEmpty, "after the lift \(othersAfterLift) also selected")

        // Slide: press Thoughts until the viewer shows, slide to Library, lift. Library opens.
        let thoughts = areaButton(app, "Thoughts"), library = areaButton(app, "Library")
        thoughts.press(forDuration: 3, thenDragTo: library)
        let slidOpened = waitUntilSelected(app, "Library", seconds: 5)
        XCTAssertTrue(slidOpened, "sliding from Thoughts to Library in the viewer did not open the Library")
        let othersAfterSlide = Self.areas.filter { $0 != "Library" && areaButton(app, $0).isSelected }
        XCTAssertTrue(othersAfterSlide.isEmpty, "after the slide \(othersAfterSlide) also selected")
        Harness.writeText("large-content-viewer-simulator.md", """
            # Large content viewer on the tab bar at AX5

            Environment: \(Harness.simulatorEnvironment(defaultLabel: "iPhone 17")), text size \
            AccessibilityXXXL (launch argument). Generated by \
            `AreaNavigationTests.testLargeContentViewerOnTabBarItem`. The Inbox tab bar item was held for \
            6 s with XCUITest `press(forDuration:)`; the host took full-screen screenshots with \
            `xcrun simctl io <udid> screenshot` (scaled to 1x with `sips`) before the press and 2.5 s into it.

            | Comparison (middle 60% x 40% of the screen) | Pixels changed by more than 24 levels | Required |
            | --- | --- | --- |
            | baseline-1 vs baseline-2 (no press; control) | \(String(format: "%.4f", control)) | below 0.01 |
            | baseline-1 vs inbox-long-press | \(String(format: "%.4f", pressed)) | above 0.04 |

            | Lift (required, as on a system tab bar) | Result |
            | --- | --- |
            | Inbox held 6 s, finger lifted on Inbox | Inbox \(openedOnLift ? "selected" : "not selected"); other items selected: \(othersAfterLift.isEmpty ? "none" : othersAfterLift.joined(separator: ", ")) |
            | Thoughts held 3 s, slid to Library, lifted | Library \(slidOpened ? "selected" : "not selected"); other items selected: \(othersAfterSlide.isEmpty ? "none" : othersAfterSlide.joined(separator: ", ")) |

            Screenshots: `screens/\(Harness.deviceFolder)/lcv/baseline-1.png`, `baseline-2.png`, \
            `inbox-long-press.png`. That the overlay shows the item's glyph and label legibly is judged \
            from the screenshot, and on a device in checklist step 12.
            """)
    }

    /// A long press on a control with the large content viewer activates it exactly once at the
    /// largest accessibility text size: the player's Play/Pause button, which toggles, so a missed
    /// activation and a double one (the Button's own action plus the lift activation) both leave the
    /// label unchanged. Presses of 0.15, 0.2, 0.35 and 3 s must each flip Pause to Play or back.
    /// At AX5 the viewer takes all of them over, so only the lift activation runs the action (a run
    /// with the activation removed fails on the first long press:
    /// `large-content-viewer-lift-mutation-simulator.md`). The 0.15 and 0.2 s presses were added in
    /// review round 3: the viewer takes a press over after about 0.15 s, and with the lift
    /// recognizer beginning only at 0.25 s such a press activated nothing. At the default text
    /// size, where the viewer is off, every press must also toggle exactly once (the Button's own
    /// action, no lift activation). Review round 3 (R3-02): at each size a 3 s press immediately
    /// followed by a tap must toggle twice, so the gate takes the tap for a new press instead of
    /// dropping it as the long press's late Button action (`large-content-viewer-mutations-simulator.md`).
    func testLargeContentViewerActivatesControlsOnce() {
        var rows: [String] = []
        for (variant, name) in [(Variant.ax5, "AX5"), (Variant.light, "Large (default)")] {
            let app = Harness.launch(["-SylviaScreen", "player"] + variant.arguments)
            defer { app.terminate() }
            XCTAssertNotNil(Harness.audit(app, name: "player"))
            var expected = "Pause"
            XCTAssertNotNil(waitForPlayPause(app, expected, seconds: 10), "\(name): no Pause button on the player")
            for duration in [0.15, 0.2, 0.35, 3.0, 0.15, 0.2, 0.35, 3.0] {
                // Scrolled wholly into view first (the transport sits below the cover at AX5).
                guard Harness.reach(app, expected, showsMiniPlayer: false, context: "\(name) player") != nil,
                      let button = playPause(app, expected) else { return }
                button.press(forDuration: duration)
                expected = expected == "Pause" ? "Play" : "Pause"
                let toggled = waitForPlayPause(app, expected, seconds: 3) != nil
                Thread.sleep(forTimeInterval: 0.5)  // a late second activation would flip it back
                let once = toggled && playPause(app, expected) != nil
                XCTAssertTrue(once, "\(name): a \(duration) s press did not toggle to \(expected) exactly once")
                rows.append("| \(name) | \(String(format: "%.2f", duration)) s | \(expected) | \(once ? "yes" : "no") |")
                if !once { return }
            }
            // Review round 3 (R3-02): a 3 s press immediately followed by a tap at the same point.
            // The tap is a new touch, so it toggles again, also when it comes within the gate's
            // late-action window after a lift activation (the gate takes a Button action for the
            // latest press whose touch lifted; were the tap taken for the long press's late Button
            // action, it would be dropped and the label would stay toggled). Two toggles bring the
            // label back.
            guard Harness.reach(app, expected, showsMiniPlayer: false, context: "\(name) player") != nil,
                  let button = playPause(app, expected) else { return }
            // A screen point, not one relative to the button: the button's query matches its label,
            // which the press changes, so an element-relative point would no longer resolve.
            let frame = button.frame
            let point = app.coordinate(withNormalizedOffset: .zero).withOffset(CGVector(dx: frame.midX, dy: frame.midY))
            let original = expected
            point.press(forDuration: 3.0)
            let lifted = Date()
            point.tap()
            let gap = Date().timeIntervalSince(lifted)
            let back = waitForPlayPause(app, original, seconds: 3) != nil
            Thread.sleep(forTimeInterval: 1.5)  // a late extra activation would flip it
            let twice = back && playPause(app, original) != nil
            XCTAssertTrue(twice, "\(name): a 3 s press followed by a tap did not toggle exactly twice (back to \(original))")
            rows.append("| \(name) | 3.00 s, then a tap (tap returned \(String(format: "%.2f", gap)) s after the press) | \(original) (toggled twice) | \(twice ? "yes" : "no") |")
            if !twice { return }
        }
        Harness.writeText("large-content-viewer-activation-simulator.md", """
            # Large content viewer: a long press activates a control exactly once

            Environment: \(Harness.simulatorEnvironment(defaultLabel: "iPhone 17")). Generated by \
            `AreaNavigationTests.testLargeContentViewerActivatesControlsOnce` on the player's Play/Pause \
            button (XCUITest `press(forDuration:)`). The button toggles, so a missed activation and a \
            double one both leave the label unchanged; each row waits 0.5 s more for a late second \
            activation. The 0.15 and 0.2 s presses (review round 3) are shorter than the 0.25 s at \
            which the lift recognizer used to begin, and longer than the viewer's own delay at AX5. \
            The last row of each text size is a 3 s press immediately followed by a tap at the same \
            point (review round 3, R3-02): the tap is a new touch and must toggle again, so the label \
            returns to where it was; the time is from the end of the press to the return of \
            XCUITest's tap, an upper bound on when the tap's touch began. The case where the Button's \
            own action arrives after the lift activation (a busy main thread) cannot be produced \
            reliably here; the gate's handling of it is proven by the unit tests \
            `liftActivationEitherOrder` and `liftActivationLimits`.

            | Text size | Press | Label expected after the press | Toggled exactly once (twice for press and tap) |
            | --- | --- | --- | --- |
            \(rows.joined(separator: "\n"))
            """)
    }

    /// The full player's Play/Pause button labelled `label`, not the mini-player's copy (the
    /// mini-player stays in the accessibility tree under the full-screen player with the same label).
    private func playPause(_ app: XCUIApplication, _ label: String) -> XCUIElement? {
        let predicate = NSPredicate(format: "label == %@", label)
        let miniPlayer = app.descendants(matching: .any)["miniPlayer"]
        let inMiniPlayer = miniPlayer.exists
            ? Set(miniPlayer.descendants(matching: .any).matching(predicate).allElementsBoundByIndex.map { "\($0.frame)" })
            : []
        return app.buttons.matching(predicate).allElementsBoundByIndex.first { !inMiniPlayer.contains("\($0.frame)") }
    }

    private func waitForPlayPause(_ app: XCUIApplication, _ label: String, seconds: Double) -> XCUIElement? {
        let deadline = Date().addingTimeInterval(seconds)
        repeat {
            if let button = playPause(app, label) { return button }
            Thread.sleep(forTimeInterval: 0.2)
        } while Date() < deadline
        return nil
    }

    // MARK: Host screenshots

    /// Asks the host helper for a screenshot named `name` after `delay` seconds; with `wait`, blocks
    /// until it is taken.
    private func requestHostScreenshot(_ name: String, delay: Double, in requests: URL, wait: Bool) throws {
        try FileManager.default.createDirectory(at: requests, withIntermediateDirectories: true)
        try? FileManager.default.removeItem(at: requests.appendingPathComponent("\(name).done"))
        try String(format: "%.1f", delay).write(to: requests.appendingPathComponent("\(name).request"),
                                                atomically: true, encoding: .utf8)
        if wait { try waitForHostScreenshot(name, in: requests) }
    }

    private func waitForHostScreenshot(_ name: String, in requests: URL) throws {
        let done = requests.appendingPathComponent("\(name).done")
        let deadline = Date().addingTimeInterval(60)
        while Date() < deadline {
            if FileManager.default.fileExists(atPath: done.path) { return }
            Thread.sleep(forTimeInterval: 0.2)
        }
        throw XCTSkip("the host screenshot helper did not answer for \(name) (run through 21-design-catalog.sh)")
    }

    /// Fraction of pixels in the middle of the screen (60% of the width, 40% of the height) whose
    /// largest channel difference exceeds 24 of 255.
    private func changedFraction(_ a: URL, _ b: URL) throws -> Double {
        let first = try XCTUnwrap(UIImage(contentsOfFile: a.path)?.cgImage, "cannot read \(a.lastPathComponent)")
        let second = try XCTUnwrap(UIImage(contentsOfFile: b.path)?.cgImage, "cannot read \(b.lastPathComponent)")
        XCTAssertEqual(first.width, second.width)
        XCTAssertEqual(first.height, second.height)
        let width = first.width, height = first.height
        func pixels(_ image: CGImage) -> [UInt8] {
            var data = [UInt8](repeating: 0, count: width * height * 4)
            let context = CGContext(data: &data, width: width, height: height, bitsPerComponent: 8,
                                    bytesPerRow: width * 4, space: CGColorSpace(name: CGColorSpace.sRGB)!,
                                    bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue)!
            context.draw(image, in: CGRect(x: 0, y: 0, width: width, height: height))
            return data
        }
        let p = pixels(first), q = pixels(second)
        var changed = 0, total = 0
        for y in Int(Double(height) * 0.3)..<Int(Double(height) * 0.7) {
            for x in Int(Double(width) * 0.2)..<Int(Double(width) * 0.8) {
                let i = (y * width + x) * 4
                let delta = max(abs(Int(p[i]) - Int(q[i])), abs(Int(p[i + 1]) - Int(q[i + 1])), abs(Int(p[i + 2]) - Int(q[i + 2])))
                if delta > 24 { changed += 1 }
                total += 1
            }
        }
        return total == 0 ? 0 : Double(changed) / Double(total)
    }
}
