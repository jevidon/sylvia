        #expect(quote.audit.texts.contains { $0.role == .reading })
    }

    // MARK: Status pills and availability badges

    @Test("Every pair of status pills differs by label; pills of different states also differ by glyph")
    func pillPairs() {
        let states = Gallery.pillStates
        var spoken: [String: String] = [:]
        var masks: [String: [Bool]] = [:]
        for (name, config) in states {
            let r = Renderer.render(StatusPill(config).padding(Spacing.l), variant: Variant(.light, .standard))
            #expect(r.elements.count == 1, "\(name): \(r.elements)")
            spoken[name] = r.elements.first?.label
            #expect(spoken[name] == config.text, "\(name): \(r.elements)")
            guard let glyph = r.audit.regions["pill.glyph"] else {
                Issue.record("\(name): no glyph region"); continue
            }
            masks[name] = GrayMeasure(r).shapeMask(in: glyph)
        }
        var table = "| Pair | Glyphs | Glyph shapes differ (cells) | Labels | Fill and text color |\n| --- | --- | --- | --- | --- |\n"
        for (i, (a, ca)) in states.enumerated() {
            for (b, cb) in states[(i + 1)...] {
                #expect(spoken[a] != spoken[b], "\(a) and \(b) read the same")
                let shape = GrayMeasure.maskDifference(masks[a] ?? [], masks[b] ?? [])
                if ca.glyph != cb.glyph {
                    #expect(shape >= 0.1, "\(a) and \(b): glyph shapes differ in only \(shape) of cells")
                } else {
                    // Same glyph: the same state family, so hue cannot separate them either; the label does.
                    #expect(ca.fill == cb.fill && ca.textColor == cb.textColor)
                }
                table += "| \(a) / \(b) | \(ca.glyph.rawValue) / \(cb.glyph.rawValue) | \(Int((shape * 100).rounded()))% | "
                    + "\(spoken[a] ?? "") / \(spoken[b] ?? "") | \(ca.fill == cb.fill ? "same" : "different") |\n"
            }
        }
        Evidence.write("t53-pill-pairs-simulator.md", text: """
            # T53 proxy: status pill pairs (\(Evidence.environmentLabel))

            Generated by `GrayscaleConformanceTests.pillPairs` over the nine pills of the import-state mapping \
            (Section 4.4.6). Every pair reads differently (labels from the accessibility tree). Pairs with \
            different glyphs (dot, check, triangle) also differ in glyph shape in the grayscale rendering \
            (threshold 10% of a 24 x 24 grid). Pairs with the same glyph belong to one family (in progress, \
            ready, or attention) and share fill and text color too, so nothing about them is carried by hue: \
            the phrase is the only and intended difference (Section 4.4.7: dot for queued, receiving, verifying, \
            preparing).

            \(table)
            """)
    }

    @Test("Availability badges differ by frame (solid or dashed) and by label")
    func availabilityBadges() {
        var table = "| Appearance | Badge | Frame runs along the top edge | Label |\n| --- | --- | --- | --- |\n"
        for variant in Self.standardVariants + [Variant(.light, .ax5)] {
            let r = Renderer.render(Gallery.sample("availabilityBadges").content, variant: variant)
            let m = GrayMeasure(r)
            for (scope, availability) in [("onDevice", Availability.onThisDevice),
                                          ("notOnDevice", .notOnThisDevice(source: "Studio")), ("recordOnly", .recordOnly)] {
                guard let rect = r.audit.regions["\(scope).badge"] else { Issue.record("no region \(scope)"); continue }
                let interior = m.mode(in: rect.insetBy(dx: rect.height / 2, dy: rect.height / 4))
                let y = m.borderRow(of: rect, interior: interior)
                let runs = m.frameRuns(y: y, from: rect.minX + rect.height / 2, to: rect.maxX - rect.height / 2,
                                       interior: interior, threshold: 1.1)
                if availability.isDashed {
                    #expect(runs >= 5, "\(variant) \(scope): \(runs) runs, expected a dashed frame")
                } else {
                    #expect(runs == 1, "\(variant) \(scope): \(runs) runs, expected a solid frame")
                }
                table += "| \(variant) | \(scope) | \(runs) | \(availability.status.text()) |\n"
            }
            let labels = r.elements.map(\.label)
            #expect(Set(labels).count == 3, "\(variant): \(labels)")
        }
        Evidence.write("t53-availability-badges-simulator.md", text: """
            # T53 proxy: availability badges (\(Evidence.environmentLabel))

            Generated by `GrayscaleConformanceTests.availabilityBadges`. Along the straight part of each badge's \
            top border in the grayscale rendering, pixels contrasting with the badge interior by at least 1.1:1 \
            are counted as runs: one run is a solid hairline, five or more a dashed one.

            \(table)
            """)
    }

    @Test("The Generated card keeps its dashed frame in grayscale; other cards have a solid hairline")
    func generatedFrame() {
        var table = "| Appearance | Card | Frame runs along the top edge |\n| --- | --- | --- |\n"
        for variant in Self.standardVariants {
            for name in ["captureCard.generated", "captureCard.quote", "captureCard.note"] {
                let r = Renderer.render(Gallery.sample(name).content, variant: variant)
                guard let card = r.audit.regions["card"] else { Issue.record("\(name): no card region"); continue }
                let m = GrayMeasure(r)
                let inset = CGFloat(Radius.card.points ?? 0)
                let interior = m.mode(in: card.insetBy(dx: inset, dy: inset))
                let y = m.borderRow(of: CGRect(x: card.minX + inset, y: card.minY, width: card.width - 2 * inset,
                                               height: 0), interior: interior)
                let runs = m.frameRuns(y: y, from: card.minX + inset, to: card.maxX - inset, interior: interior,
                                       threshold: 1.1)
                if name == "captureCard.generated" {
                    #expect(runs >= 10, "\(variant): generated frame shows \(runs) runs")
                } else {
                    #expect(runs == 1, "\(variant) \(name): \(runs) runs")
                }
                table += "| \(variant) | \(name) | \(runs) |\n"
            }
        }
        Evidence.write("t53-generated-frame-simulator.md", text: """
            # T53 proxy: Generated frame (\(Evidence.environmentLabel))

            Generated by `GrayscaleConformanceTests.generatedFrame`: runs of frame pixels (contrast with the card \
            interior at least 1.1:1) along the straight part of each card's top border in the grayscale rendering.

            \(table)
            """)
    }

    // MARK: Buttons

    @Test("\"Saving…\" is drawn at full contrast: its fill equals the enabled button's, its label 4.5:1 (R1-03)")
    func busySaveButtonKeepsContrast() {
        for variant in Self.standardVariants + [Variant(.light, .ax5)] {
            let r = Renderer.render(Gallery.sample("captureSheet.saveStates").content, variant: variant)
            let m = GrayMeasure(r)
            var fills: [String: UInt8] = [:]
            for state in ["draft", "saving", "saved", "failed"] {
                guard let rect = r.audit.regions["\(state).button.primary.fill"] else {
                    Issue.record("\(variant): no fill region for \(state): \(r.audit.regions.keys.sorted())"); continue
                }
                let inner = rect.insetBy(dx: 4, dy: 4)
                let fill = m.mode(in: inner)
                let label = m.extreme(in: inner, against: fill)
                fills[state] = fill
                let labelVsFill = Grayscale.contrast(label, fill)
                #expect(labelVsFill >= 4.5, "\(variant) \(state): label vs fill \(labelVsFill)")
            }
            #expect(fills["saving"] != nil && fills["saving"] == fills["draft"],
                    "\(variant): the busy fill \(String(describing: fills["saving"])) is faded against \(String(describing: fills["draft"]))")
        }
    }

    @Test("In grayscale the primary fill stays distinct from ink text and from hairline secondary buttons")
    func buttonsInGrayscale() {
        var table = """
            | Appearance | Ground | Primary fill | Primary label | Ink text (secondary label) | Secondary border | Destructive border | Fill vs ground | Label vs fill | Fill vs ink text | Secondary border vs ground | Destructive border vs ground |
            | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |

            """
        var secondaryBorder: [Appearance: Double] = [:]
        for variant in Self.standardVariants {
            let r = Renderer.render(Gallery.sample("buttons").content, variant: variant)
            let m = GrayMeasure(r)
            guard let primary = r.audit.regions["primary.button.primary"],
                  let secondary = r.audit.regions["secondary.button.secondary"],
                  let destructive = r.audit.regions["destructive.button.destructive"] else {
                Issue.record("\(variant): button regions missing: \(r.audit.regions.keys.sorted())"); continue
            }
            let ground = m.mode()
            let inner = { (rect: CGRect) in rect.insetBy(dx: 4, dy: 4) }
            let fill = m.mode(in: inner(primary))
            let label = m.extreme(in: inner(primary), against: fill)
            let secondaryInterior = m.mode(in: inner(secondary))
            let inkText = m.extreme(in: inner(secondary), against: secondaryInterior)
            // The 1 pt border at the button's leading edge, at mid-height.
            let edge = { (rect: CGRect) in CGRect(x: rect.minX, y: rect.midY - 2, width: 1.5, height: 4) }
            let border = m.extreme(in: edge(secondary), against: secondaryInterior)
            let destructiveBorder = m.extreme(in: edge(destructive), against: m.mode(in: inner(destructive)))

            let fillVsGround = Grayscale.contrast(fill, ground)
            let labelVsFill = Grayscale.contrast(label, fill)
            let fillVsInk = Grayscale.contrast(fill, inkText)
            let borderVsGround = Grayscale.contrast(border, ground)
            let destructiveVsGround = Grayscale.contrast(destructiveBorder, ground)
            secondaryBorder[variant.appearance] = borderVsGround

            // WCAG 1.4.11 (non-text contrast) for the fill against the page; 1.4.3 for its label.
            #expect(fillVsGround >= 3, "\(variant): primary fill vs ground \(fillVsGround)")
            #expect(labelVsFill >= 4.5, "\(variant): primary label vs fill \(labelVsFill)")
            // A filled block and ink text must not collapse to the same grey (ADR-0013 §9: 1.5:1).
            #expect(fillVsInk >= 1.5, "\(variant): primary fill vs ink text \(fillVsInk)")
            // The secondary button has no fill: its interior is the ground, and its hairline is visible.
            #expect(secondaryInterior == ground, "\(variant): secondary interior \(secondaryInterior) vs ground \(ground)")
            #expect(borderVsGround > 1.1, "\(variant): secondary border vs ground \(borderVsGround)")
            #expect(destructiveVsGround >= 3, "\(variant): destructive border vs ground \(destructiveVsGround)")
            table += "| \(variant) | \(ground) | \(fill) | \(label) | \(inkText) | \(border) | \(destructiveBorder) | "
                + "\(ratio(fillVsGround)) | \(ratio(labelVsFill)) | \(ratio(fillVsInk)) | \(ratio(borderVsGround)) | \(ratio(destructiveVsGround)) |\n"
        }
        // Increase Contrast raises the hairline from 12% to 24%: the border must get stronger.
        for (standard, increased) in [(Appearance.light, Appearance.lightIncreasedContrast), (.dark, .darkIncreasedContrast)] {
            if let s = secondaryBorder[standard], let i = secondaryBorder[increased] {
                #expect(i > s, "\(increased): hairline \(i) is not stronger than \(s)")
            }
        }
        Evidence.write("t53-buttons-grayscale-simulator.md", text: """
            # T53 proxy: button roles in grayscale (\(Evidence.environmentLabel))

            Generated by `GrayscaleConformanceTests.buttonsInGrayscale` from the grayscale rendering of the \
            `buttons` sample (default text size). Levels are 8-bit grey (sRGB-encoded luminance); ratios are WCAG \
            contrast ratios between those levels, which equal the ratios of the original colors.

            Thresholds: primary fill vs ground at least 3:1 (WCAG 1.4.11); primary label vs fill at least 4.5:1; \
            primary fill vs ink text at least 1.5:1 (proposed in ADR-0013 Section 9 so a filled button never reads \
            as text); secondary interior equal to the ground (no fill) and its hairline above 1.1:1; destructive \
            border at least 3:1; the hairline stronger under Increase Contrast than without it.

            \(table)
            """)
    }

    // MARK: Rating

    @Test("Filled, half and outline stars stay distinct in grayscale")
    func ratingStars() {
        var table = "| Appearance | Full coverage | Half coverage | Empty coverage |\n| --- | --- | --- | --- |\n"
        for variant in Variant.matrix {
            let r = Renderer.render(Gallery.sample("rating").content, variant: variant)
            let m = GrayMeasure(r)
            let ground = m.mode()
            func coverage(_ scope: String, _ index: Int) -> Double? {
                r.audit.regions["\(scope).rating.star\(index)"].map { m.coverage(in: $0, background: ground, threshold: 1.5) }
            }
            // "nine" = 4.5 stars: four full, one half. "four" = 2 stars: two full, three empty.
            let full = (0..<4).compactMap { coverage("nine", $0) } + (0..<2).compactMap { coverage("four", $0) }
            let half = [coverage("nine", 4)].compactMap { $0 }
            let empty = (2..<5).compactMap { coverage("four", $0) } + (0..<5).compactMap { coverage("none", $0) }
            guard full.count == 6, half.count == 1, empty.count == 8 else {
                Issue.record("\(variant): star regions missing (\(full.count), \(half.count), \(empty.count))"); continue
            }
            let minFull = full.min()!, maxEmpty = empty.max()!, h = half[0]
            #expect(minFull >= 1.5 * maxEmpty, "\(variant): full \(minFull) vs empty \(maxEmpty)")
            #expect(h >= 1.15 * maxEmpty && h <= 0.9 * minFull, "\(variant): half \(h) between \(maxEmpty) and \(minFull)")
            table += "| \(variant) | \(ratio(minFull)) (min) | \(ratio(h)) | \(ratio(maxEmpty)) (max) |\n"
        }
        Evidence.write("t53-rating-grayscale-simulator.md", text: """
            # T53 proxy: rating stars in grayscale (\(Evidence.environmentLabel))

            Generated by `GrayscaleConformanceTests.ratingStars`: the share of each star's area whose grey level \
            contrasts with the ground by at least 1.5:1, in the grayscale rendering. Pass: every full star covers \
            at least 1.5x the most-covered empty star, and the half star lies between (at least 1.15x empty, at \
            most 0.9x full).

            \(table)
            """)
    }
}

@Suite("T51 layout at the largest accessibility size")
@MainActor
struct LayoutConformanceTests {
    static let variants = [Variant(.light, .standard), Variant(.light, .ax5), Variant(.light, .ax5, boldText: true)]

    @Test("Control: the audit flags a truncated label and a label pushed off the canvas")
    func auditDetectsClipping() {
        let truncated = Renderer.render(Text(SampleText.quote).sylviaFont(.body).lineLimit(1).frame(width: 200)
                                            .padding(Spacing.l), variant: Variant(.light, .ax5))
        #expect(truncated.audit.texts.count == 1)
        #expect(truncated.audit.texts.allSatisfy { $0.isTruncated }, "\(truncated.audit.texts)")
        let pushed = Renderer.render(Text(LabelKey.controlCaptureRecent.localized).sylviaFont(.body).fixedSize()
                                         .frame(width: 100), variant: Variant(.light, .ax5), width: 120)
        #expect(pushed.audit.texts.contains { $0.frame.minX < -0.5 || $0.frame.maxX > 120.5 }, "\(pushed.audit.texts)")
        let fits = Renderer.render(Text(SampleText.quote).sylviaFont(.body).fixedSize(horizontal: false, vertical: true)
                                       .padding(Spacing.l), variant: Variant(.light, .ax5))
        #expect(fits.audit.texts.count == 1 && !fits.audit.texts.contains { $0.isTruncated })
    }

    @Test("No styled label is truncated or runs outside the canvas", arguments: Gallery.names)
    func noClippedLabels(_ name: String) {
        let sample = Gallery.sample(name)
        var lines: [String] = []
        for variant in Self.variants {
            let r = Renderer.render(sample.content, variant: variant, width: sample.width, height: sample.height,
                                    sizeClass: sample.sizeClass)
            let texts = r.audit.texts
            #expect(r.audit.incompleteReports == 0, "\(name) \(variant): \(r.audit.incompleteReports) texts reported only half")
            if name != "typographicCover" {
                #expect(!texts.isEmpty, "\(name) \(variant): no styled text was audited")
            }
            let truncated = texts.filter(\.isTruncated)
            let outside = texts.filter { $0.frame.minX < -0.5 || $0.frame.maxX > sample.width + 0.5 }
            let elementsOutside = r.elements.filter { $0.frame.minX < -0.5 || $0.frame.maxX > sample.width + 0.5 }
            #expect(truncated.isEmpty, "\(name) \(variant): truncated \(truncated)")
            #expect(outside.isEmpty, "\(name) \(variant): outside the canvas \(outside)")
            #expect(elementsOutside.isEmpty, "\(name) \(variant): accessibility elements outside \(elementsOutside)")
            lines.append("| \(name) | \(variant) | \(texts.count) | \(truncated.count) | \(outside.count) | \(Int(r.size.height)) |")
        }
        LayoutReport.shared.add(name, lines)
    }
}

/// Collects the T51 rows and writes them when all samples have reported.
@MainActor
final class LayoutReport {
    static let shared = LayoutReport()
    private var rows: [String: [String]] = [:]

    func add(_ name: String, _ lines: [String]) {
        rows[name] = lines
        guard rows.count == Gallery.names.count else { return }
        let body = Gallery.names.flatMap { rows[$0] ?? [] }.joined(separator: "\n")
        Evidence.write("t51-layout-audit-simulator.md", text: """
            # T51 proxy: labels at the default and largest accessibility size (\(Evidence.environmentLabel))

            Generated by `LayoutConformanceTests.noClippedLabels`. Every text set in a type role reports its \
            laid-out frame and the height it needs at that width with no line limit; it is truncated when it \
            got less. Variants: light at the default size (Large), at AX5 (accessibilityExtraExtraExtraLarge), \
            and at AX5 with Bold Text. Canvas width 402 pt (iPhone 17) except the sidebar (320 pt). Bars (tab \
            bar, navigation bar, reader chrome top row) stop growing at xxxLarge by design and rely on the \
            large content viewer. Typographic covers are objects that scale with their width and are not audited.

            | Sample | Variant | Texts audited | Truncated | Outside the canvas | Height (pt) |
            | --- | --- | --- | --- | --- | --- |
            \(body)
            """)
    }
}
