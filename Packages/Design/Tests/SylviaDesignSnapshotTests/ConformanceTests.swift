    // MARK: Markers

    @Test("Every pair of markers differs by glyph and by label, not only by hue")
    func markerPairs() {
        let markers = Marker.allCases
        var spoken: [Marker: String] = [:]
        var masks: [Marker: [Bool]] = [:]
        for marker in markers {
            // The accessibility tree of a marker row: one element whose label starts with the
            // marker's label.
            let row = Renderer.render(MarkerRow(.init(marker: marker, details: ["Walden"])).padding(Spacing.l),
                                      variant: Variant(.light, .standard))
            #expect(row.elements.count == 1, "\(marker): \(row.elements)")
            spoken[marker] = row.elements.first?.label
            #expect(spoken[marker]?.hasPrefix(marker.labelKey.localized) == true, "\(marker): \(row.elements)")
            // The glyph alone, in grayscale, as a shape mask.
            let glyph = Renderer.render(MarkerGlyph(marker, role: .heading).padding(Spacing.l),
                                        variant: Variant(.light, .standard), width: 120)
            masks[marker] = GrayMeasure(glyph).shapeMask(in: CGRect(origin: .zero, size: glyph.size))
        }
        var table = "| Pair | Glyphs | Glyph shapes differ in grayscale (cells) | Labels (spoken) | Same text color |\n| --- | --- | --- | --- | --- |\n"
        for (i, a) in markers.enumerated() {
            for b in markers[(i + 1)...] {
                let glyphDiffers = a.glyph.identifier != b.glyph.identifier
                let shapeDifference = GrayMeasure.maskDifference(masks[a]!, masks[b]!)
                let labelDiffers = a.labelKey.localized != b.labelKey.localized && spoken[a] != spoken[b]
                let sameColor = a.textColor.value(in: .light) == b.textColor.value(in: .light)
                #expect(glyphDiffers, "\(a) and \(b) share a glyph")
                #expect(shapeDifference >= 0.1, "\(a) and \(b) glyph shapes differ in only \(shapeDifference) of cells")
                #expect(labelDiffers, "\(a) and \(b) share a label")
                table += "| \(a.rawValue) / \(b.rawValue) | \(a.glyph.identifier) / \(b.glyph.identifier) | "
                    + "\(Int((shapeDifference * 100).rounded()))% | \(spoken[a] ?? "") / \(spoken[b] ?? "") | \(sameColor ? "yes" : "no") |\n"
            }
        }
        Evidence.write("t53-marker-pairs-simulator.md", text: """
            # T53 proxy: marker pairs (\(Evidence.environmentLabel))

            Generated by `GrayscaleConformanceTests.markerPairs`. For each of the 21 pairs of the seven markers: \
            the glyph identifiers differ, the glyphs' shapes differ in the grayscale rendering (share of a 24 x 24 \
            grid that differs after cropping each glyph to its ink; threshold 10%), and the spoken labels from the \
            accessibility tree differ. "Same text color" shows pairs that hue cannot separate at all (Quote and \
            Word share the quote color family).

            \(table)
            """)
    }

    @Test("Control: identical glyphs give identical shape masks")
    func measurementControls() {
        let a = Renderer.render(MarkerGlyph(.note, role: .heading).padding(Spacing.l), variant: Variant(.light, .standard), width: 120)
        let b = Renderer.render(MarkerGlyph(.note, role: .heading).padding(Spacing.l), variant: Variant(.light, .standard), width: 120)
        let maskA = GrayMeasure(a).shapeMask(in: CGRect(origin: .zero, size: a.size))
        #expect(maskA.contains(true), "the mask found ink")
        #expect(GrayMeasure.maskDifference(maskA, GrayMeasure(b).shapeMask(in: CGRect(origin: .zero, size: b.size))) == 0)
    }

    @Test("Quote and Audio cards differ by content form: Literata text versus a play control and waveform")
    func quoteVersusAudio() {
        let quote = Renderer.render(Gallery.sample("captureCard.quote").content, variant: Variant(.light, .standard))
        let audio = Renderer.render(Gallery.sample("captureCard.audio").content, variant: Variant(.light, .standard))
        #expect(quote.audit.regions["quote.block"] != nil)
        #expect(quote.audit.regions["audio.play"] == nil)
        #expect(audio.audit.regions["audio.play"] != nil && audio.audit.regions["audio.waveform"] != nil)
        #expect(audio.audit.regions["quote.block"] == nil)
        #expect(audio.elements.contains { $0.isButton && $0.label == LabelKey.controlPlayExcerpt.localized })
        #expect(!quote.elements.contains { $0.isButton })
