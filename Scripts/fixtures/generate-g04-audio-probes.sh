#!/usr/bin/env bash
# Generates the G0.4 container probe fixtures into $SYLVIA_FIXTURE_CACHE/generated/g04-audio/probes (review R5-08: two
# container behaviours ADR-0006 relies on had been seen only in host probes while the fixtures were built; these files
# let the simulator tests show them, ContainerProbeTests).
#
#   Scripts/fixtures/generate-g04-audio-fixtures.sh    # first: the masters (master-600s.wav)
#   Scripts/fixtures/generate-g04-audio-probes.sh      # then: this script (idempotent; a few seconds)
#   Scripts/fixtures/generate-g04-audio-probes.sh --force   # rebuild
#
# Content. Each file is the first 60 s of master-600s.wav (public-domain LibriVox Meditations; Fixtures/LICENSES.md)
# with one chapter table, Opening at 0 s, Chapter Two at 20 s and Chapter Three at 40 s, written as Vorbis comments in
# three numberings, in native FLAC and in Ogg Opus (the two containers whose chapters are Vorbis comments):
#   chapters-3digit-001.flac/.ogg   CHAPTER001, CHAPTER001NAME, ...   (the chapter extension's form; the main fixtures')
#   chapters-3digit-000.flac/.ogg   CHAPTER000, CHAPTER000NAME, ...   (the same form, numbered from 000)
#   chapters-2digit-01.flac/.ogg    CHAPTER01, CHAPTER01NAME, ...     (two digits)
# The other behaviour, AVAssetWriter refusing MP3 packets in MPEG-4, is probed with the main script's MP3 files.
#
# Determinism and robustness as in the main script: bitexact flags, temporary names renamed on success, SHA-256 per
# file in manifest.tsv, and a stamp of this script, ffmpeg, macOS and the master that triggers a rebuild on change.
#
# Requires: ffmpeg/ffprobe (Homebrew, with libopus), shasum, and the main script's output.
set -euo pipefail
source "$(cd "$(dirname "$0")/../lib" && pwd)/env.sh"

BASE="$SYLVIA_FIXTURE_CACHE/generated/g04-audio"
OUT="$BASE/probes"
M600="$BASE/master-600s.wav"

force=0
[[ "${1:-}" == "--force" ]] && force=1

for tool in ffmpeg ffprobe shasum; do
  command -v "$tool" >/dev/null || { echo "missing tool: $tool (brew install ffmpeg)" >&2; exit 1; }
done
[[ -f "$BASE/.stamp" && -f "$M600" ]] || { echo "missing $M600; run Scripts/fixtures/generate-g04-audio-fixtures.sh first" >&2; exit 1; }

FFMPEG_VERSION="$(ffmpeg -version | head -1)"
MACOS_VERSION="$(sw_vers -productVersion) ($(sw_vers -buildVersion))"
SCRIPT_SHA="$(shasum -a 256 "$0" | awk '{print $1}')"
MASTER_SHA="$(shasum -a 256 "$M600" | awk '{print $1}')"
STAMP="$SCRIPT_SHA|$FFMPEG_VERSION|$MACOS_VERSION|$MASTER_SHA"

mkdir -p "$OUT"
if [[ -f "$OUT/.stamp" && "$(cat "$OUT/.stamp")" == "$STAMP" && $force -eq 0 ]]; then
  echo "g04 probe fixtures are current in $OUT"
  exit 0
fi
echo "# Command: ${0#"$SYLVIA_ROOT"/}${1:+ $1}; started $(date -u +%Y-%m-%dT%H:%M:%SZ)"
echo "# Environment: host, macOS $MACOS_VERSION, $(sysctl -n machdep.cpu.brand_string 2>/dev/null || echo 'unknown CPU'), $FFMPEG_VERSION"
rm -f "$OUT/.stamp"
find "$OUT" -name '.tmp-*' -delete

ff() { ffmpeg -nostdin -hide_banner -v error -y "$@"; }
BITEXACT=(-fflags +bitexact -flags:a +bitexact)
tmp() { echo "$OUT/.tmp-$1"; }
commit() { mv -f "$(tmp "$1")" "$OUT/$1"; echo "  $1"; }

# chapters <digits> <first number>: the -metadata arguments for the table in that numbering.
chapters() {
  local digits="$1" first="$2" i=0 n
  local -a starts=("00:00:00.000" "00:00:20.000" "00:00:40.000") titles=("Opening" "Chapter Two" "Chapter Three")
  for i in 0 1 2; do
    n="$(printf "%0${digits}d" $((first + i)))"
    printf '%s\0%s\0%s\0%s\0' -metadata "CHAPTER$n=${starts[$i]}" -metadata "CHAPTER${n}NAME=${titles[$i]}"
  done
}

for form in "3digit-001 3 1" "3digit-000 3 0" "2digit-01 2 1"; do
  read -r name digits first <<<"$form"
  args=()
  while IFS= read -r -d '' a; do args+=("$a"); done < <(chapters "$digits" "$first")
  ff -i "$M600" -t 60 -c:a flac -metadata title="Sylvia G04 chapter probe" "${args[@]}" "${BITEXACT[@]}" -map_metadata -1 "$(tmp "chapters-$name.flac")"
  commit "chapters-$name.flac"
  ff -i "$M600" -t 60 -c:a libopus -b:a 32k -metadata title="Sylvia G04 chapter probe" "${args[@]}" "${BITEXACT[@]}" -map_metadata -1 "$(tmp "chapters-$name.ogg")"
  commit "chapters-$name.ogg"
done

echo "manifest"
{
  echo "# Generated by Scripts/fixtures/generate-g04-audio-probes.sh"
  echo "# ffmpeg: $FFMPEG_VERSION"
  echo "# macOS: $MACOS_VERSION"
  # ffmpeg's own Vorbis-comment reader turns CHAPTERnn and CHAPTERnnn comments alike into chapters (and drops them
  # from the tags), so the last column is what ffprobe reads, not what AVFoundation reads (ContainerProbeTests).
  printf '# file\tsha256\tbytes\tffprobe duration (s)\tcodec\tchapters ffprobe reads (start s, title)\n'
  (cd "$OUT" && find . -type f ! -name '.*' \( -name '*.flac' -o -name '*.ogg' \) | sed 's|^\./||' | LC_ALL=C sort) |
  while read -r f; do
    sha="$(shasum -a 256 "$OUT/$f" | awk '{print $1}')"
    bytes="$(stat -f %z "$OUT/$f")"
    dur="$(ffprobe -v error -show_entries format=duration -of default=nw=1:nk=1 "$OUT/$f")"
    codec="$(ffprobe -v error -select_streams a:0 -show_entries stream=codec_name -of default=nw=1:nk=1 "$OUT/$f")"
    chapters="$(ffprobe -v error -show_entries chapter=start_time:chapter_tags=title -of csv=p=0 "$OUT/$f" | paste -sd ';' - || true)"
    printf '%s\t%s\t%s\t%s\t%s\t%s\n' "$f" "$sha" "$bytes" "$dur" "$codec" "$chapters"
  done
} > "$OUT/manifest.tsv"
cat "$OUT/manifest.tsv"
echo "$STAMP" > "$OUT/.stamp"
echo "done: $OUT"
